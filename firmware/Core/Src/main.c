float adc_phase_a(void) {
    /* read one phase current via ADC1 (two-shunt or integrated sense) */
    HAL_ADC_Start(&hadc1);
    if (HAL_ADC_PollForConversion(&hadc1, 10) == HAL_OK)
        return (float)HAL_ADC_GetValue(&hadc1) * 0.001f; /* scale to A */
    return 0.0f;
}

float adc_phase_b(void) {
    return 0.0f;   /* placeholder: second phase or reconstruct from i_a+i_b */
}

uint16_t spi1_read_word(uint8_t reg) {
    uint8_t tx[2] = { (uint8_t)(0x40 | (reg >> 6)), (uint8_t)(reg << 2) };
    uint8_t rx[2] = { 0, 0 };
    HAL_GPIO_WritePin(ENC1_CS_GPIO_Port, ENC1_CS_Pin, GPIO_PIN_RESET);
    HAL_SPI_TransmitReceive(&hspi1, tx, rx, 2, 10);
    HAL_GPIO_WritePin(ENC1_CS_GPIO_Port, ENC1_CS_Pin, GPIO_PIN_SET);
    return (uint16_t)((rx[0] << 8) | rx[1]);
}

uint16_t spi2_read_word(uint8_t reg) {
    uint8_t tx[2] = { (uint8_t)(0x40 | (reg >> 6)), (uint8_t)(reg << 2) };
    uint8_t rx[2] = { 0, 0 };
    HAL_GPIO_WritePin(ENC2_CS_GPIO_Port, ENC2_CS_Pin, GPIO_PIN_RESET);
    HAL_SPI_TransmitReceive(&hspi2, tx, rx, 2, 10);
    HAL_GPIO_WritePin(ENC2_CS_GPIO_Port, ENC2_CS_Pin, GPIO_PIN_SET);
    return (uint16_t)((rx[0] << 8) | rx[1]);
}

